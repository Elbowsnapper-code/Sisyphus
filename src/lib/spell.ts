const dict = new Set(
  COMMON.split(/\s+/).filter(Boolean).map((w) => w.toLowerCase().replace(/['']/g, "'")),
);

const SKIP = /^(?:[A-Z]{2,}|[A-Za-z]|\d+)$/;

export function tokenizeWords(text: string): string[] {
  return text.match(/[A-Za-z][A-Za-z'-]*/g) ?? [];
}

export function extraDictionary(values: string[]): Set<string> {
  const set = new Set<string>();
  for (const value of values) {
    for (const word of tokenizeWords(value)) {
      if (word.length > 1) set.add(word.toLowerCase().replace(/['']/g, "'"));
    }
  }
  return set;
}

export function unknownWords(html: string, extras?: Set<string>): string[] {
  const text = htmlToPlain(html);
  const seen = new Set<string>();
  const out: string[] = [];
  for (const raw of tokenizeWords(text)) {
    if (raw.length < 2) continue;
    if (SKIP.test(raw) && raw.length <= 3) continue;
    if (/^[A-Z]/.test(raw)) continue;
    const key = raw.toLowerCase().replace(/['']/g, "'");
    if (seen.has(key)) continue;
    seen.add(key);
    if (dict.has(key)) continue;
    if (extras?.has(key)) continue;
    out.push(raw);
  }
  return out;
}

export function misspellingCounts(html: string, extras?: Set<string>): Map<string, number> {
  const text = htmlToPlain(html);
  const counts = new Map<string, number>();
  for (const raw of tokenizeWords(text)) {
    if (raw.length < 2) continue;
    if (SKIP.test(raw) && raw.length <= 3) continue;
    if (/^[A-Z]/.test(raw)) continue;
    const key = raw.toLowerCase().replace(/['']/g, "'");
    if (dict.has(key)) continue;
    if (extras?.has(key)) continue;
    counts.set(key, (counts.get(key) ?? 0) + 1);
  }
  return counts;
}

export function addToDictionary(word: string) {
  const key = word.toLowerCase().replace(/['']/g, "'");
  if (key.length > 1) dict.add(key);
}

export function projectDictionary(
  docs: Record<string, Doc>,
  projectId: string,
  extra: string[] = [],
): Set<string> {
  const values = [...extra];
  for (const doc of Object.values(docs)) {
    const inProject =
      doc.id === projectId ||
      doc.parentId === projectId ||
      (doc.parentId && docs[doc.parentId]?.parentId === projectId) ||
      (doc.parentId && docs[doc.parentId] && docs[docs[doc.parentId].parentId ?? ""]?.parentId === projectId);
    if (!inProject) continue;
    if (doc.title) values.push(doc.title);
    if (doc.sheet?.name) values.push(doc.sheet.name);
    if (doc.sheet?.aliases) values.push(doc.sheet.aliases);
    if (doc.titlePage) {
      values.push(doc.titlePage.authorName, doc.titlePage.bookTitle, doc.titlePage.seriesName);
    }
    for (const rule of doc.autoReplace ?? []) values.push(rule.to, rule.from);
  }
  return extraDictionary(values);
}
